-- E9-01 integration checks. Fake users/data only; all writes roll back.
-- Run with: supabase db query --local --file supabase/tests/authorization.sql
begin;
set local plpgsql.check_asserts = on;
do $$
declare
  fa uuid := gen_random_uuid(); fb uuid := gen_random_uuid();
  wa uuid := gen_random_uuid(); wb uuid := gen_random_uuid(); peer uuid := gen_random_uuid();
  reviewer uuid := gen_random_uuid(); admin_user uuid := gen_random_uuid(); pending uuid := gen_random_uuid();
  ca uuid := gen_random_uuid(); cb uuid := gen_random_uuid(); inf_id uuid := gen_random_uuid();
  sess uuid := gen_random_uuid(); n integer := 0; got jsonb; c jsonb; i jsonb; uid uuid;
begin
  insert into public.facilities(id,name) values (fa,'FAKE authorization test A '||fa), (fb,'FAKE authorization test B '||fb);
  foreach uid in array array[wa, wb, peer, reviewer, admin_user, pending] loop
    insert into auth.users(id,email) values (uid, 'fake-'||uid||'@example.invalid');
  end loop;
  assert (select count(*) from public.profiles where id = any(array[wa,wb,peer,reviewer,admin_user,pending])) = 6, 'Signup creates profiles'; n:=n+1;
  assert (select facility_id is null and role='health_worker' from public.profiles where id=pending), 'Signup cannot self-assign a facility'; n:=n+1;
  update public.profiles set facility_id=fa where id in (wa,peer);
  update public.profiles set facility_id=fb where id=wb;
  update public.profiles set facility_id=fa,role='reviewer' where id=reviewer;
  update public.profiles set role='admin' where id=admin_user;
  insert into public.cases(id,facility_id,created_by,age_band,client_version) values(cb,fb,wb,'35-44',1);
  insert into auth.sessions(id,user_id) values(sess,wa);
  assert (select count(*) from public.audit_log where action='sign_in' and actor=wa and entity_id=sess)=1, 'Sign-in logged once'; n:=n+1;
  assert not exists(select 1 from pg_class t join pg_namespace s on s.oid=t.relnamespace where s.nspname='public' and t.relname in ('facilities','profiles','cases','inferences','audit_log') and not t.relrowsecurity), 'All slice tables have RLS'; n:=n+1;
  assert not has_table_privilege('anon','public.cases','SELECT'), 'Anonymous table access revoked'; n:=n+1;
  assert not has_table_privilege('authenticated','public.cases','SELECT'), 'Case reads cannot bypass audit RPC'; n:=n+1;
  assert not has_table_privilege('authenticated','public.inferences','UPDATE'), 'Inference edits revoked'; n:=n+1;
  set local role anon;
  begin perform public.list_cases(); raise exception 'Anonymous RPC unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  reset role;
  perform set_config('request.jwt.claim.sub', pending::text, true);
  set local role authenticated;
  begin perform public.list_cases(); raise exception 'Unassigned account unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  reset role;
  perform set_config('request.jwt.claim.sub',wa::text,true);
  set local role authenticated;
  assert (select count(*) from public.profiles)=1, 'Only own profile visible'; n:=n+1;
  assert (select count(*) from public.facilities)=1, 'Only assigned facility visible'; n:=n+1;
  begin update public.profiles set role='admin' where id=wa; raise exception 'Self-promotion unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  begin perform public.save_case(jsonb_build_object('id',ca,'age_band','25-34','client_version',1,'facility_id',fb)); raise exception 'Client facility override unexpectedly allowed'; exception when invalid_parameter_value then n:=n+1; end;
  c:=jsonb_build_object('id',ca,'age_band','25-34','symptoms','{}'::jsonb,'notes','FAKE demo case','client_version',1);
  got:=public.save_case(c);
  assert (got->>'facility_id')::uuid=fa and (got->>'created_by')::uuid=wa, 'Server assigns trusted facility and author'; n:=n+1;
  assert (public.save_case(c)->>'client_version')::int=1, 'Repeated save accepted'; n:=n+1;
  begin perform public.save_case(c||'{"notes":"different content"}'); raise exception 'Version collision unexpectedly allowed'; exception when invalid_parameter_value then n:=n+1; end;
  got:=public.save_case(c||'{"client_version":2,"notes":"FAKE updated"}');
  assert got->>'notes'='FAKE updated', 'New version updates case'; n:=n+1;
  assert (public.save_case(c)->>'client_version')::int=2, 'Stale replay does not overwrite newer case'; n:=n+1;
  begin perform public.save_case(jsonb_build_object('id',cb,'age_band','35-44','client_version',2)); raise exception 'Cross-facility write unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  assert public.get_case(cb) is null, 'Cross-facility read returns no data'; n:=n+1;
  assert jsonb_array_length(public.list_cases())=1, 'List contains own-facility case only'; n:=n+1;
  begin perform public.list_cases(101,0); raise exception 'Unbounded list unexpectedly allowed'; exception when invalid_parameter_value then n:=n+1; end;
  i:=jsonb_build_object('id',inf_id,'case_id',ca,'model_name','demo-tb','model_version','demo-only','thresholds_version','demo-only','outputs','{"tb_probability":0.2}'::jsonb,'zone','unsure','quality_scores','{"passed":true}'::jsonb,'latency_ms',12.5);
  got:=public.append_inference(i);
  assert (got->>'id')::uuid=inf_id, 'Inference saved'; n:=n+1;
  assert (public.append_inference(i)->>'id')::uuid=inf_id, 'Inference replay accepted'; n:=n+1;
  begin perform public.append_inference(i||'{"zone":"refer_now"}'); raise exception 'Inference mutation unexpectedly allowed'; exception when invalid_parameter_value then n:=n+1; end;
  begin perform public.append_inference((i-'thresholds_version')||jsonb_build_object('id',gen_random_uuid())); raise exception 'Unversioned inference unexpectedly allowed'; exception when not_null_violation then n:=n+1; end;
  begin perform public.append_inference(i||jsonb_build_object('id',gen_random_uuid(),'case_id',cb)); raise exception 'Cross-facility inference unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  got:=public.get_case(ca);
  assert jsonb_array_length(got->'inferences')=1, 'Audited read includes inference'; n:=n+1;
  assert (select count(*) from public.audit_log)=0, 'Worker cannot read audit log'; n:=n+1;
  reset role;
  assert (select count(*) from public.audit_log where entity_id=ca and action='insert' and actor=wa)=1, 'Case replay does not duplicate creation audit'; n:=n+1;
  assert (select count(*) from public.audit_log where entity_id=ca and action='update' and actor=wa)=1, 'Update audit is exactly once'; n:=n+1;
  assert (select count(*) from public.audit_log where entity_id=inf_id and action='insert' and actor=wa)=1, 'Inference replay does not duplicate audit'; n:=n+1;
  assert (select count(*) from public.audit_log where entity_id=ca and action='access' and actor=wa)=2, 'Each successful get/list access logged exactly once'; n:=n+1;
  begin update public.inferences set zone='refer_now' where id=inf_id; raise exception 'Immutable inference trigger failed'; exception when insufficient_privilege then n:=n+1; end;
  begin delete from public.audit_log where entity_id=ca; raise exception 'Append-only audit trigger failed'; exception when insufficient_privilege then n:=n+1; end;
  perform set_config('request.jwt.claim.sub',peer::text,true);
  set local role authenticated;
  assert public.get_case(ca) is not null, 'Peer worker in same facility can read case'; n:=n+1;
  reset role;
  perform set_config('request.jwt.claim.sub',wb::text,true);
  set local role authenticated;
  assert public.get_case(ca) is null, 'Facility B cannot read facility A'; n:=n+1;
  reset role;
  foreach uid in array array[reviewer,admin_user] loop
    perform set_config('request.jwt.claim.sub',uid::text,true);
    set local role authenticated;
    begin perform public.get_case(ca); raise exception 'Non-worker row-level access unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
    reset role;
  end loop;
  perform set_config('request.jwt.claim.sub',admin_user::text,true);
  set local role authenticated;
  assert (select count(*) from public.audit_log)>0, 'Admin can read audit trail'; n:=n+1;
  reset role;
  update public.profiles set disabled_at=now() where id=wa;
  perform set_config('request.jwt.claim.sub',wa::text,true);
  set local role authenticated;
  begin perform public.get_case(ca); raise exception 'Disabled worker unexpectedly allowed'; exception when insufficient_privilege then n:=n+1; end;
  reset role;
  raise notice 'Passed % authorization, audit and idempotency checks; rolling back fake fixtures', n;
  perform set_config('triagelens.test_summary', 'Passed '||n||' checks',true);
end;
$$;
select current_setting('triagelens.test_summary') as test_result;
rollback;
